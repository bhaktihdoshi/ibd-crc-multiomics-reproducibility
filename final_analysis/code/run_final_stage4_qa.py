def check_pytest_suites() -> dict:
    suites = [
        Path(__file__).parent.parent / "tests" / "test_corrected_v2_integrity.py",
    ]
    results = []
    all_ok = True
    for suite in suites:
        if not suite.exists():
            results.append({"suite": str(suite), "status": "NOT_FOUND"})
            all_ok = False
            continue
        proc = subprocess.run([sys.executable, "-m", "pytest", str(suite), "-q"], capture_output=True, text=True)
        ok = proc.returncode == 0
        all_ok = all_ok and ok
        results.append({"suite": str(suite), "status": "PASS" if ok else "FAIL", "tail": proc.stdout.strip().splitlines()[-3:]})
    return {"ok": all_ok, "suites": results}


def check_authoritative_files_unmutated() -> dict:
    if not AUTHORITATIVE_FILES_CSV.exists():
        return {"ok": False, "reason": "authoritative files registry not found"}
    reg = read_csv(AUTHORITATIVE_FILES_CSV)
    mismatches, missing = [], []
    for _, row in reg.iterrows():
        path = Path(row["path"])
        if not path.exists():
            missing.append(str(path))
            continue
        live_hash = sha256(path)
        if str(row["sha256"]) != live_hash:
            mismatches.append({"path": str(path), "frozen_sha256": row["sha256"], "live_sha256": live_hash})
    return {"ok": not mismatches and not missing, "n_checked": len(reg), "missing": missing, "mutated_since_freeze": mismatches}


def check_no_duplicate_participants_and_reclosure() -> dict:
    issues = []
    for cohort in ["Franzosa", "iHMP", "Sinha", "Yachida"]:
        path = V2 / "data" / "processed" / f"{cohort.lower()}_authoritative_genus_proportions.csv"
        if not path.exists():
            issues.append(f"{cohort}: authoritative genus table not found at {path}")
            continue
        df = read_csv(path)
        if df["sample_id"].duplicated().any():
            issues.append(f"{cohort}: duplicate sample_id values present")
        abundances = df.drop(columns=["sample_id"])
        # pandas' .sum() silently skips NaN, so a corrupted/unresolved-missing
        # cell would otherwise still pass a naive row-sum-to-1 check. Require
        # every cell to be finite (no NaN, no +/-inf) before trusting the sum.
        if not np.isfinite(abundances.to_numpy()).all():
            n_bad = int((~np.isfinite(abundances.to_numpy())).sum())
            issues.append(f"{cohort}: {n_bad} non-finite (NaN/inf) cells in authoritative genus matrix")
            continue
        row_sums = abundances.sum(axis=1)
        if not np.allclose(row_sums, 1.0, atol=1e-6):
            issues.append(f"{cohort}: rows do not re-close to 1 (max abs deviation {float((row_sums - 1).abs().max()):.2e})")
    return {"ok": not issues, "issues": issues}


def check_cohort_counts_match_metadata() -> dict:
    """Cross-check the frozen table1 case/control counts against a fresh
    build_xy() call for the MICROBIOME representation (the smallest, most
    restrictive matched set), using the same cohort-matching and IBD-label
    collapsing (CD/UC -> IBD) logic the pipeline itself applies, rather than
    reinventing the harmonisation rules independently."""
    if not TABLE1_CSV.exists():
        return {"ok": False, "reason": "table1_cohort_and_assay_overview.csv not found"}
    table1 = read_csv(TABLE1_CSV).set_index("cohort")
    from run_stage4b_corrected_v2b import build_xy

    bundle = CorrectedDataBundle()
    cohort_specs = {
        "Franzosa": [s for s in TASK_SPECS if s.disease == "IBD" and s.train_cohort == "Franzosa"][0],
        "iHMP": [s for s in TASK_SPECS if s.disease == "IBD" and s.train_cohort == "iHMP"][0],
        "Sinha": [s for s in TASK_SPECS if s.disease == "CRC" and s.train_cohort == "Sinha"][0],
        "Yachida": [s for s in TASK_SPECS if s.disease == "CRC" and s.train_cohort == "Yachida"][0],
    }
    mismatches = []
    for cohort, spec in cohort_specs.items():
        _, y, _ = build_xy(bundle, spec, cohort, "MICROBIOME")
        live_case, live_control = int(y.sum()), int((1 - y).sum())
        expected_case, expected_control = int(table1.loc[cohort, "case_n"]), int(table1.loc[cohort, "control_n"])
        if (live_case, live_control) != (expected_case, expected_control):
            mismatches.append({"cohort": cohort, "table1": (expected_case, expected_control), "live_matched_microbiome_set": (live_case, live_control)})
    return {"ok": not mismatches, "mismatches": mismatches}


def check_non_finite_values() -> dict:
    issues = []
    n_files_checked = 0
    for path, whitelisted_columns in NON_FINITE_SCAN_TARGETS:
        if not path.exists():
            issues.append(f"{path}: not found")
            continue
        n_files_checked += 1
        df = read_csv(path)
        numeric = df.select_dtypes(include=[np.number]).drop(columns=[c for c in whitelisted_columns if c in df.columns], errors="ignore")
        n_bad = int((~np.isfinite(numeric.to_numpy())).sum()) if not numeric.empty else 0
        if n_bad:
            issues.append(f"{path}: {n_bad} non-finite numeric cells (outside whitelisted columns {whitelisted_columns})")
    return {"ok": not issues, "n_files_checked": n_files_checked, "issues": issues}


def check_final_reporting_validation_table() -> dict:
    if not REPORTING_VALIDATION_CSV.exists():
        return {"ok": False, "reason": "final_stage4_reporting_validation_tests.csv not found"}
    df = read_csv(REPORTING_VALIDATION_CSV)
    if "status" not in df.columns:
        return {"ok": False, "reason": "reporting validation table has no 'status' column"}
    failing = df[~df["status"].eq("pass")]
    return {"ok": failing.empty, "n_checks": len(df), "failing_rows": failing.to_dict(orient="records")}


def check_load_bearing_code_hashes() -> dict:
    """Records (does not verify against a baseline) sha256 hashes of the
    scripts that actually generate the authoritative outputs, so a future run
    of this QA suite can diff which analysis code changed since this run.
    This is NOT an equivalence proof — see the module docstring."""
    hashes = {}
    missing = []
    for name in LOAD_BEARING_SCRIPTS:
        path = SCRIPTS / name
        if not path.exists():
            missing.append(name)
            continue
        hashes[name] = sha256(path)
    return {"ok": not missing, "missing_scripts": missing, "sha256": hashes}


def check_feature_order_identical_at_transfer() -> dict:
    bundle = CorrectedDataBundle()
    issues = []
    for spec in TASK_SPECS:
        for rep in REPRESENTATIONS:
            try:
                X_train, _, _, X_ext, _, _ = aligned_train_external(bundle, spec, rep)
            except ValueError as exc:
                issues.append(f"{spec.task} {spec.train_cohort}->{spec.external_cohort} {rep}: {exc}")
                continue
            if list(X_train.columns) != list(X_ext.columns):
                issues.append(f"{spec.task} {spec.train_cohort}->{spec.external_cohort} {rep}: feature order mismatch")
    return {"ok": not issues, "issues": issues}


def check_fixed_seed_reproducibility() -> dict:
    from run_stage4b_corrected_v2b import cross_fitted_decision_scores_and_probs
    from stage4_corrected_v2_common import fold_count, INNER_FOLDS

    bundle = CorrectedDataBundle()
    spec = TASK_SPECS[0]
    X, y, _, _, _, _ = aligned_train_external(bundle, spec, "MICROBIOME")
    seed = 20260813
    s1, p1 = cross_fitted_decision_scores_and_probs(X, y, "MICROBIOME", 1.0, fold_count(y, INNER_FOLDS), seed)
    s2, p2 = cross_fitted_decision_scores_and_probs(X, y, "MICROBIOME", 1.0, fold_count(y, INNER_FOLDS), seed)
    identical = np.array_equal(s1, s2) and np.array_equal(p1, p2)
    return {"ok": identical, "note": "same seed refit twice; decision scores must be bit-identical"}


def check_figure_source_provenance() -> dict:
    if not FIGURE_SOURCE_CSV.exists():
        return {"ok": False, "reason": "final_stage4_figure_source_values.csv not found"}
    df = read_csv(FIGURE_SOURCE_CSV)
    source_cols = [c for c in df.columns if "csv" in c.lower() or "source" in c.lower() or "path" in c.lower()]
    missing = []
    for col in source_cols:
        for value in df[col].dropna().astype(str):
            if value.endswith(".csv") and not Path(value).exists():
                missing.append(value)
    return {"ok": not missing, "n_rows": len(df), "source_columns_checked": source_cols, "missing_referenced_csvs": sorted(set(missing))}


def main() -> None:
    checks = {
        "pytest_suites": check_pytest_suites(),
        "authoritative_files_unmutated": check_authoritative_files_unmutated(),
        "no_duplicate_participants_and_reclosure": check_no_duplicate_participants_and_reclosure(),
        "cohort_counts_match_metadata": check_cohort_counts_match_metadata(),
        "non_finite_values": check_non_finite_values(),
        "feature_order_identical_at_transfer": check_feature_order_identical_at_transfer(),
        "fixed_seed_reproducibility": check_fixed_seed_reproducibility(),
        "figure_source_provenance": check_figure_source_provenance(),
        "final_reporting_validation_table": check_final_reporting_validation_table(),
        "load_bearing_code_hashes_recorded": check_load_bearing_code_hashes(),
    }
    overall_ok = all(v.get("ok", False) for v in checks.values())
    report = {"overall_status": "PASS" if overall_ok else "FAIL", "checks": checks}
    atomic_json(report, REPORTS / "final_stage4_qa_report.json")
    for name, result in checks.items():
        print(f"[{'PASS' if result.get('ok') else 'FAIL'}] {name}")
    print(f"\nOverall: {'PASS' if overall_ok else 'FAIL'}")
    print(f"Full report: {REPORTS / 'final_stage4_qa_report.json'}")
    if not overall_ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
