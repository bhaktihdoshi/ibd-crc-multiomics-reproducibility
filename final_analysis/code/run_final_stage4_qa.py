"""Single consolidated final-QA entrypoint for the frozen Stage 4 pipeline.

IMPORTANT SCOPE CAVEAT: this script proves that (a) the frozen authoritative
output *files* have not changed since the 20 August freeze, and (b) a set of
independent, cheap, targeted checks currently pass against the live code and
data. It does NOT prove "the current live code generated the frozen tables"
— `stage4_corrected_v2_common.py` and other scripts have been edited after
the freeze (see `POST_FREEZE_CODE_PATCH_MANIFEST.json`, generated by
`generate_post_freeze_patch_manifest.py`), so the code state and the frozen
output state are no longer literally the same snapshot. It does not hash
every executable dependency of every frozen table, and it does not
re-execute the full nested-CV/MOFA/sCCA/GCN chain to reproduce every number.
`check_load_bearing_code_hashes()` below only *records* current hashes for
future-diff purposes; it is not an equivalence proof. For a real equivalence
argument see `run_stage4_post_freeze_equivalence_check.py`.

This also does not reimplement Stage 4's own hardening (nested-CV leakage,
decision-score metrics, threshold freezing, etc.) — those already live as
targeted unit tests in `corrected_v2/tests/test_corrected_v2_integrity.py`
and as dedicated audit scripts (`audit_stage4b_corrected_v2b_*`,
`audit_stage4d_corrected_v2_provenance_topology.py`, ...). What was missing
was a *single* command that runs all of it and reports one pass/fail
verdict, so a discrepancy between code and thesis text can't slip through
because a check existed but nobody ran it. This script:

  1. Runs the corrected_v2 pytest suite (all leakage/decision-score/
     threshold/graph/task-scope/authoritative-source tests) and records
     pass/fail counts.
  2. Verifies every file in `final_stage4_authoritative_files.csv` exists
     and its live sha256 still matches the value frozen at authority-freeze
     time (catches silent post-freeze mutation of an authoritative output).
  3. Checks each authoritative genus-proportion table for duplicate
     `sample_id` values, no non-finite/unresolved-NaN cells, and re-closure
     to 1 (explicit isfinite/isna check first, since pandas' .sum() silently
     skips NaN and would otherwise let a corrupted row pass a naive row-sum
     check).
  4. Cross-checks cohort case/control counts in
     `table1_cohort_and_assay_overview.csv` against the live metadata files.
  5. Scans a broad set of authoritative/prediction/performance CSVs across
     Stage 4A-4E (not just Stage 4B) for non-finite (NaN/inf) numeric cells,
     with an explicit whitelist for columns/files where missing values are a
     structurally expected outcome (e.g. a bootstrap CI that legitimately
     could not be computed) rather than silently ignoring all NaN globally.
  6. Re-derives, for each Stage 4B TaskSpec/representation, that train and
     external feature columns are identical and in the same order (the same
     invariant `aligned_train_external` enforces at run time, checked here
     independently of that code path).
  7. Spot-checks fixed-seed reproducibility: refits one small nested-CV
     inner loop twice with the same seed and confirms bit-for-bit identical
     decision scores.
  8. Confirms every row of `final_stage4_figure_source_values.csv` (the
     main-text-number -> CSV provenance map) points at a CSV that exists.
  9. Confirms `final_stage4_reporting_validation_tests.csv` itself contains
     no failing rows (the final reporting validation layer is included in
     the consolidated verdict, not left as a separate check nobody runs).
  10. Records sha256 hashes of the load-bearing pipeline scripts into the
      report, so a future re-run can diff which analysis code changed.

Nothing here trains a GCN or runs a heavy sweep — everything is either a
file check or a few seconds of small logistic-regression refitting. Meant
to be run manually from the terminal before the thesis numbers are treated
as final.
"""

